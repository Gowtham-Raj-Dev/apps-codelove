/*
  Sync the Android flavors with src/data/apps.js.

    node tools/sync-apps.mjs          (run from src/android-apps)

  Writes
    app/apps.json                                  → read by app/build.gradle.kts (one product flavor per app)
    app/src/<flavor>/res/drawable/ic_launcher_foreground.xml
    app/src/<flavor>/res/drawable/ic_splash.xml    → generated from the app's Lucide icon

  Run it again whenever you add an app, change a version, accent or icon.
*/

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");          // src/android-apps
const website = path.resolve(root, "../..");    // app-website

const { apps } = await import(pathToFileURL(path.join(website, "src/data/apps.js")).href);
const { site } = await import(pathToFileURL(path.join(website, "src/data/site.js")).href);

// Gradle flavor names must be plain identifiers (no "-")
const flavorName = (id) => id.replace(/[^a-z0-9]/gi, "").toLowerCase();

// "linear-gradient(135deg, #7c6cff 0%, #b18cff 100%)" → ["#7c6cff", "#b18cff"]
function gradientStops(gradient, fallback) {
  const stops = (gradient || "").match(/#[0-9a-f]{6}/gi) || [];
  return [stops[0] || fallback, stops[1] || stops[0] || fallback];
}

function versionCode(version) {
  const [a = 0, b = 0, c = 0] = version.split(".").map((n) => parseInt(n, 10) || 0);
  return a * 10000 + b * 100 + c;
}

// ---------------------------------------------------------------- icons

// Convert a Lucide icon (SVG node list) into Android VectorDrawable <path> elements
function lucideToPaths(node) {
  const out = [];
  const stroke = (d, extra = "") =>
    out.push(
      `        <path android:pathData="${d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round"${extra} />`,
    );
  for (const [tag, a] of node) {
    const n = (k) => parseFloat(a[k] ?? 0);
    switch (tag) {
      case "path":
        stroke(a.d);
        break;
      case "line":
        stroke(`M${n("x1")},${n("y1")}L${n("x2")},${n("y2")}`);
        break;
      case "polyline":
      case "polygon": {
        const pts = a.points.trim().split(/[\s,]+/).map(Number);
        let d = `M${pts[0]},${pts[1]}`;
        for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]},${pts[i + 1]}`;
        if (tag === "polygon") d += "Z";
        stroke(d);
        break;
      }
      case "circle": {
        const cx = n("cx"), cy = n("cy"), r = n("r");
        stroke(`M${cx - r},${cy}a${r},${r} 0 1,0 ${r * 2},0a${r},${r} 0 1,0 ${-r * 2},0`);
        break;
      }
      case "ellipse": {
        const cx = n("cx"), cy = n("cy"), rx = n("rx"), ry = n("ry");
        stroke(`M${cx - rx},${cy}a${rx},${ry} 0 1,0 ${rx * 2},0a${rx},${ry} 0 1,0 ${-rx * 2},0`);
        break;
      }
      case "rect": {
        const x = n("x"), y = n("y"), w = n("width"), h = n("height");
        const r = Math.min(n("rx") || n("ry") || 0, w / 2, h / 2);
        if (r > 0) {
          stroke(
            `M${x + r},${y}h${w - 2 * r}a${r},${r} 0 0,1 ${r},${r}v${h - 2 * r}a${r},${r} 0 0,1 ${-r},${r}h${-(w - 2 * r)}a${r},${r} 0 0,1 ${-r},${-r}v${-(h - 2 * r)}a${r},${r} 0 0,1 ${r},${-r}z`,
          );
        } else {
          stroke(`M${x},${y}h${w}v${h}h${-w}z`);
        }
        break;
      }
      default:
        console.warn(`  ! unsupported svg element <${tag}> skipped`);
    }
  }
  return out.join("\n");
}

// "ClipboardList" → "clipboard-list", "ImageIcon" → "image" (lucide-react aliases *Icon)
function lucideFile(name) {
  const base = name.replace(/Icon$/, "");
  return base.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();
}

async function loadLucide(name) {
  const file = path.join(website, "node_modules/lucide-react/dist/esm/icons", `${lucideFile(name)}.mjs`);
  const mod = await import(pathToFileURL(file).href);
  return mod.__iconData.node;
}

const header = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/sync-apps.mjs from src/data/apps.js — do not edit by hand -->`;

function launcherForeground(paths) {
  return `${header}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="2.1" android:scaleY="2.1" android:translateX="28.8" android:translateY="28.8">
${paths}
    </group>
</vector>
`;
}

function splashIcon(paths) {
  return `${header}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M30,22h48a8,8 0,0 1,8 8v48a8,8 0,0 1,-8 8H30a8,8 0,0 1,-8 -8V30a8,8 0,0 1,8 -8z">
        <aapt:attr name="android:fillColor">
            <gradient android:startX="22" android:startY="22" android:endX="86" android:endY="86" android:type="linear">
                <item android:offset="0" android:color="@color/brand" />
                <item android:offset="1" android:color="@color/brand_light" />
            </gradient>
        </aapt:attr>
    </path>
    <group android:scaleX="1.5" android:scaleY="1.5" android:translateX="36" android:translateY="36">
${paths}
    </group>
</vector>
`;
}

// ---------------------------------------------------------------- run

const entries = [];
for (const app of apps) {
  const flavor = flavorName(app.id);
  const [accent, accentLight] = gradientStops(app.icon?.gradient, app.accent || "#7c6cff");
  const webPath = app.webAppUrl || `/${app.id}/app`;
  const url = new URL(webPath, site.url);

  entries.push({
    flavor,
    id: app.id,
    name: app.name,
    versionName: app.version,
    versionCode: versionCode(app.version),
    url: url.href,
    host: url.host,
    deepLinkPath: url.pathname,
    accent: accent.toUpperCase(),
    accentLight: accentLight.toUpperCase(),
  });

  if (app.icon?.name) {
    const dir = path.join(root, "app/src", flavor, "res/drawable");
    await mkdir(dir, { recursive: true });
    const paths = lucideToPaths(await loadLucide(app.icon.name));
    await writeFile(path.join(dir, "ic_launcher_foreground.xml"), launcherForeground(paths));
    await writeFile(path.join(dir, "ic_splash.xml"), splashIcon(paths));
  }
  console.log(`✓ ${flavor.padEnd(12)} ${app.name.padEnd(12)} v${app.version.padEnd(7)} ${url.href}`);
}

await writeFile(path.join(root, "app/apps.json"), JSON.stringify(entries, null, 2) + "\n");
console.log(`\n${entries.length} apps → app/apps.json`);
console.log("Build one:  .\\build-app.ps1 <id>      e.g.  .\\build-app.ps1 clipdropper");
