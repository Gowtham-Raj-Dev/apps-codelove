/*
  List the APKs in public/downloads/ so the site knows which apps can be downloaded.

    node scripts/sync-downloads.mjs     (build-app.ps1 -Publish runs it for you)

  Writes src/data/downloads.js: { "<app id>": { bytes, sha256, built } }.
  An app built by src/android-apps shows "Coming soon" until its APK is listed here.
*/
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "public/downloads");

const list = {};
for (const name of (await readdir(dir)).filter((f) => f.endsWith(".apk")).sort()) {
  const file = path.join(dir, name);
  const info = await stat(file);
  list[name.replace(/\.apk$/, "")] = {
    bytes: info.size,
    sha256: createHash("sha256").update(await readFile(file)).digest("hex"),
    built: info.mtime.toISOString().slice(0, 10),
  };
}

await writeFile(
  path.join(root, "src/data/downloads.js"),
  `// GENERATED by scripts/sync-downloads.mjs — do not edit by hand\nexport const downloads = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`${Object.keys(list).length} APKs → src/data/downloads.js`);
